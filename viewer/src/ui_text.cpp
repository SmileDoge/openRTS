void set_ui_language(const UiLanguage language) noexcept {
    current = language;
}

UiLanguage ui_language() noexcept {
    return current;
}

const char* tr(const char* english) {
    if (!english || current == UiLanguage::english) return english;
    const auto& table = russian();
    if (const auto it = table.find(english); it != table.end()) return it->second;
    // "label##id": the label translated, the id kept (the UI thread only).
    const std::string_view text(english);
    const auto hashes = text.find("##");
    if (hashes == std::string_view::npos || hashes == 0) return english;
    const auto it = table.find(text.substr(0, hashes));
    if (it == table.end()) return english;
    static std::unordered_map<std::string, std::string> joined;
    auto& slot = joined[std::string(text)];
    if (slot.empty()) slot = std::string(it->second) + std::string(text.substr(hashes));
    return slot.c_str();
}

std::string trf(const char* english, ...) {
    char buffer[512];
    va_list arguments;
    va_start(arguments, english);
    std::vsnprintf(buffer, sizeof buffer, tr(english), arguments);
    va_end(arguments);
    return buffer;
}

